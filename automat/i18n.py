class I18n:
    def __init__(self, lang="ru"):
        self._lang = lang if lang in LANGUAGES else "ru"

    @property
    def lang(self):
        return self._lang

    @lang.setter
    def lang(self, value):
        if value in LANGUAGES:
            self._lang = value

    def tr(self, key, **kwargs):
        translations = TRANSLATIONS.get(self._lang, TRANSLATIONS["ru"])
        text = translations.get(key, TRANSLATIONS["ru"].get(key, key))
        if kwargs:
            return text.format(**kwargs)
        return text
